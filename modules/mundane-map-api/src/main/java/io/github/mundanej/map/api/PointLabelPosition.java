package io.github.mundanej.map.api;

/** Center or compass position of a point label relative to its translated anchor bounds. */
public enum PointLabelPosition {
    /** Centered on the selected anchor basis. */
    CENTER,
    /** North. */
    N,
    /** North-east. */
    NE,
    /** East. */
    E,
    /** South-east. */
    SE,
    /** South. */
    S,
    /** South-west. */
    SW,
    /** West. */
    W,
    /** North-west. */
    NW
}
