package io.github.mundanej.map.api;

/** Native WKT2 coordinate-system axis direction. */
public enum CrsAxisDirection {
    /** Increasing east. */
    EAST,
    /** Increasing west. */
    WEST,
    /** Increasing north. */
    NORTH,
    /** Increasing south. */
    SOUTH,
    /** Increasing upward. */
    UP,
    /** Increasing downward. */
    DOWN
}
